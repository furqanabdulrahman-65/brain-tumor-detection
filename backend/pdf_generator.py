                # Cr (x=0.75)
                y_val += peaks.get("Creatine", 0) * 0.2 * math.exp(-100 * (x_norm - 0.75)**2)
                # Cho (x=0.8)
                y_val += peaks.get("Choline", 0) * 0.2 * math.exp(-100 * (x_norm - 0.8)**2)
                
                # Scale Y
