        if "fmri" not in analytics:
            # Deterministic Fallback
            import math
            import random
            loc = analytics.get("localization", "").lower()
            func_area = "Unknown / Subcortical"
            if "frontal" in loc: func_area = "Prefrontal Cortex"
            elif "temporal" in loc: func_area = "Temporal Lobe"
            elif "parietal" in loc: func_area = "Parietal Lobe"
            elif "cerebellum" in loc: func_area = "Cerebellum"
            
            # Simulate Signal
            bold_signal = []
            for t in range(50):
                val = math.sin(2 * math.pi * 0.1 * t)
                if report.prediction_label == "Tumor Detected":
                    val = val * 0.7 + (random.random() - 0.5) * 0.4
                else:
                    val += (random.random() - 0.5) * 0.1
                bold_signal.append(round(val, 3))
                
            networks = {"Default Mode": "Intact", "Salience": "Intact", "Executive Control": "Intact", "Sensorimotor": "Intact"}
            if report.prediction_label == "Tumor Detected":
                networks["Executive Control"] = "Compromised" if "frontal" in loc else "Intact"
            
            analytics["fmri"] = {
                "region": func_area,
                "bold_signal": bold_signal,
                "networks": networks,
                "interpretation": "Projected functional deficit based on lesion location." if report.prediction_label == "Tumor Detected" else "Normal functional connectivity."
            }

