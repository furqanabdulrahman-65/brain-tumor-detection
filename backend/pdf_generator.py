def on_page(canvas, doc):
    canvas.saveState()
    w, h = letter
    
    # 1. Header Background (Full Width)
    canvas.setFillColor(THEME["primary"])
    canvas.rect(0, h - 1.5*inch, w, 1.5*inch, fill=1, stroke=0)
    
    # 2. Logo / Brand
    canvas.setFillColor(THEME["white"])
    canvas.setFont("Helvetica-Bold", 20)
    canvas.drawString(0.6*inch, h - 0.8*inch, "NeuroScan AI")
    
    canvas.setFont("Helvetica", 10)
    canvas.setFillColor(colors.HexColor('#94A3B8')) # Slate 400
    canvas.drawString(0.6*inch, h - 1.05*inch, "Advanced Automated Neurological Diagnostics")
    
    # 3. Report Badge (Right)
    canvas.setFont("Helvetica-Bold", 14)
    canvas.setFillColor(THEME["white"])
    canvas.drawRightString(w - 0.6*inch, h - 0.75*inch, "DIAGNOSTIC REPORT")
    
    canvas.setFont("Helvetica", 9)
    canvas.setFillColor(colors.HexColor('#94A3B8'))
    # Use formatted date
    date_str = datetime.now().strftime("%B %d, %Y | %H:%M UTC")
    canvas.drawRightString(w - 0.6*inch, h - 1.05*inch, date_str)
    
    # 4. Header Decorative Line
    canvas.setStrokeColor(THEME["accent"])
    canvas.setLineWidth(3)
    canvas.line(0, h - 1.5*inch, w, h - 1.5*inch)
    
    # 5. Footer Layout
    # Thin line
    canvas.setStrokeColor(THEME["border"])
    canvas.setLineWidth(1)
    canvas.line(0.5*inch, 0.75*inch, w - 0.5*inch, 0.75*inch)
    
    # Footer Text
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(THEME["muted"])
    canvas.drawString(0.5*inch, 0.5*inch, "CONFIDENTIAL: This report is generated by an AI reference system. It does not replace professional medical advice.")
    canvas.drawString(0.5*inch, 0.4*inch, "NeuroScan AI v2.0 | Engine: EfficientNetV2 + SVM | ID: NSAI-GEN-2024")
    
    canvas.drawRightString(w - 0.5*inch, 0.5*inch, f"Page {doc.page}")

    canvas.restoreState()

